@app.put("/api/projects/{project_id}/code")
async def upload_project_code(project_id: int, request: Request, filename: str, user_id: int = Depends(authenticated_user)):
    # ZIP 使用原始请求体传输；检查扩展名、大小和压缩包格式后存入 Oracle BLOB。
    if not filename.lower().endswith(".zip"):
        raise HTTPException(status_code=400, detail="项目代码仅支持 ZIP 文件")
    content = await request.body()
    if len(content) > 20 * 1024 * 1024:
        raise HTTPException(status_code=413, detail="ZIP 文件不能超过 20 MB")
    if not zipfile.is_zipfile(io.BytesIO(content)):
        raise HTTPException(status_code=400, detail="文件内容不是有效的 ZIP 压缩包")
    safe_name = Path(filename).name[:255]
    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.setinputsizes(content=oracledb.DB_TYPE_BLOB)
            cursor.execute("UPDATE experiences SET project_zip=:content,project_zip_name=:filename WHERE id=:id AND user_id=:user_id AND category='project'",
                content=content, filename=safe_name, id=project_id, user_id=user_id)
            if cursor.rowcount == 0:
                raise HTTPException(status_code=404, detail="项目不存在")
        connection.commit()
    return {"code": 0, "msg": "项目代码 ZIP 已保存", "data": {"filename": safe_name}}


@app.get("/api/projects/{project_id}/code")
def download_project_code(project_id: int, user_id: int = Depends(authenticated_user)):
    # 下载前同时按项目 ID 和用户 ID 查询，确保只能取回自己的项目文件。
    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT project_zip,project_zip_name FROM experiences WHERE id=:id AND user_id=:user_id AND category='project'",
                id=project_id, user_id=user_id)
            row = cursor.fetchone()
            if row is None or row[0] is None:
                raise HTTPException(status_code=404, detail="项目代码 ZIP 不存在")
            content = row[0].read() if hasattr(row[0], "read") else bytes(row[0])
            filename = row[1] or "project.zip"
    encoded_name = filename.encode("utf-8").hex()
    return Response(content=content, media_type="application/zip", headers={
        "Content-Disposition": f"attachment; filename=project.zip; filename*=UTF-8''{__import__('urllib.parse').parse.quote(filename)}",
        "X-Project-Filename-Hex": encoded_name,
    })


