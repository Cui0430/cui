@app.post("/api/register")
def register(payload: StudentCredentials):
    student_id, name = payload.student_id.strip(), payload.name.strip()
    if not student_id or not name:
        raise HTTPException(status_code=422, detail="学号和姓名不能为空")
    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT id FROM users WHERE student_id=:student_id", student_id=student_id)
            if cursor.fetchone():
                raise HTTPException(status_code=409, detail="该学号已经注册")
            username = "student_" + hashlib.sha256(student_id.encode("utf-8")).hexdigest()[:24]
            cursor.execute("""INSERT INTO users (username,password_hash,user_role,name,student_id)
                VALUES (:username,:password_hash,'student',:name,:student_id)""",
                username=username, password_hash=secrets.token_urlsafe(48), name=name, student_id=student_id)
            cursor.execute("SELECT id FROM users WHERE student_id=:student_id", student_id=student_id)
            user_id = int(cursor.fetchone()[0])
            cursor.execute("INSERT INTO profiles (user_id) VALUES (:user_id)", user_id=user_id)
        connection.commit()
    user_data = {"id": user_id, "student_id": student_id, "name": name, "role": "student"}
    return {"code": 0, "msg": "注册成功", "data": user_data, "token": create_token(user_id)}


@app.post("/api/login")
def login(payload: StudentCredentials):
    # 学号与姓名匹配后签发 JWT；后续个人资料/经历接口用 JWT 识别当前用户。
    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT id,student_id,name FROM users WHERE student_id=:student_id AND name=:name",
                student_id=payload.student_id.strip(), name=payload.name.strip())
            user = cursor.fetchone()
            if user is None:
                raise HTTPException(status_code=401, detail="学号或姓名不匹配，请先注册")
            user_id = int(user[0])
            cursor.execute("SELECT COUNT(*) FROM profiles WHERE user_id=:user_id", user_id=user_id)
            if cursor.fetchone()[0] == 0:
                cursor.execute("INSERT INTO profiles (user_id) VALUES (:user_id)", user_id=user_id)
        connection.commit()
    user_data = {"id": user_id, "student_id": user[1], "name": user[2], "role": "student"}
    return {"code": 0, "msg": "登录成功", "data": user_data, "token": create_token(user_id)}


@app.get("/api/profile")
def get_profile(user_id: int = Depends(authenticated_user)):
    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""SELECT u.student_id,u.name,p.university,p.major,p.grade,p.bio
                FROM users u JOIN profiles p ON p.user_id=u.id WHERE u.id=:user_id""", user_id=user_id)
            row = cursor.fetchone()
    if row is None:
        raise HTTPException(status_code=404, detail="个人资料不存在")
    data = {"student_id": row[0], "name": row[1], "university": row[2] or "", "major": row[3] or "", "grade": row[4] or "", "bio": row[5] or ""}
    return {"code": 0, "data": data}


