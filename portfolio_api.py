@contextmanager
def database_connection():
    # 每次 API 调用按需建立连接；with 结束后自动关闭连接。
    with oracledb.connect(user=DB_USER, password=DB_PASSWORD, dsn=DB_DSN) as connection:
        yield connection


def initialize_database():
    # 应用启动时创建缺失表，并为旧 experiences 表补上项目 ZIP 字段。
    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM user_tables WHERE table_name='USERS'")
            if cursor.fetchone()[0] == 0:
                cursor.execute("""CREATE TABLE users (
                    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR2(50) UNIQUE NOT NULL,
                    password_hash VARCHAR2(200) NOT NULL,
                    user_role VARCHAR2(20) NOT NULL,
                    name VARCHAR2(100) NOT NULL,
                    student_id VARCHAR2(50),
                    phone VARCHAR2(30),
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                    CONSTRAINT users_role_check CHECK (user_role IN ('student','admin'))
                )""")
            for column, statement in (
                ("STUDENT_ID", "ALTER TABLE users ADD (student_id VARCHAR2(50))"),
                ("NAME", "ALTER TABLE users ADD (name VARCHAR2(100))"),
            ):
                cursor.execute("SELECT COUNT(*) FROM user_tab_columns WHERE table_name='USERS' AND column_name=:column_name", column_name=column)
                if cursor.fetchone()[0] == 0:
                    cursor.execute(statement)
            for table_name, statement in (
                ("PROFILES", """CREATE TABLE profiles (
                    user_id NUMBER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                    university VARCHAR2(150), major VARCHAR2(150), grade VARCHAR2(50),
                    bio VARCHAR2(1000), updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
                )"""),
                ("EXPERIENCES", """CREATE TABLE experiences (
                    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id NUMBER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    category VARCHAR2(20) NOT NULL,
                    title VARCHAR2(200) NOT NULL,
                    organization VARCHAR2(200), start_date VARCHAR2(20), end_date VARCHAR2(20),
                    description VARCHAR2(2000),
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                    CONSTRAINT experiences_category_check CHECK (category IN ('campus','award','project'))
                )"""),
            ):
                cursor.execute("SELECT COUNT(*) FROM user_tables WHERE table_name=:table_name", table_name=table_name)
                if cursor.fetchone()[0] == 0:
                    cursor.execute(statement)
            for column, statement in (
                ("PROJECT_ZIP", "ALTER TABLE experiences ADD (project_zip BLOB)"),
                ("PROJECT_ZIP_NAME", "ALTER TABLE experiences ADD (project_zip_name VARCHAR2(255))"),
            ):
                cursor.execute("SELECT COUNT(*) FROM user_tab_columns WHERE table_name='EXPERIENCES' AND column_name=:column_name", column_name=column)
                if cursor.fetchone()[0] == 0:
                    cursor.execute(statement)
        connection.commit()


def create_token(user_id: int) -> str:
    expires = datetime.now(timezone.utc) + timedelta(hours=8)
    return jwt.encode({"sub": str(user_id), "exp": expires}, JWT_SECRET, algorithm="HS256")


def authenticated_user(credentials: HTTPAuthorizationCredentials | None = Depends(auth_scheme)) -> int:
    # 从 Authorization: Bearer <token> 读取 JWT，校验签名与过期时间并提取用户 ID。
    if credentials is None:
        raise HTTPException(status_code=401, detail="请先登录")
    try:
        claims = jwt.decode(credentials.credentials, JWT_SECRET, algorithms=["HS256"])
        return int(claims["sub"])
    except (jwt.PyJWTError, KeyError, ValueError):
        raise HTTPException(status_code=401, detail="登录已过期，请重新登录")


class StudentCredentials(BaseModel):
    student_id: str = Field(min_length=1, max_length=50)
    name: str = Field(min_length=1, max_length=100)


class ProfileInput(BaseModel):
    university: str = Field(default="", max_length=150)
    major: str = Field(default="", max_length=150)
    grade: str = Field(default="", max_length=50)
    bio: str = Field(default="", max_length=1000)


class ExperienceInput(BaseModel):
    # Pydantic 会在进入接口函数前验证 JSON 字段、长度和类别取值。
    category: str = Field(pattern="^(campus|award|project)$")
    title: str = Field(min_length=1, max_length=200)
    organization: str = Field(default="", max_length=200)
    start_date: str = Field(default="", max_length=20)
    end_date: str = Field(default="", max_length=20)
    description: str = Field(default="", max_length=2000)


